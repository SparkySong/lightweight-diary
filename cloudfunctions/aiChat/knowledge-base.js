// 匹配知识库：命中返回答案，未命中返回 null（交由 AI 回答）
function matchKnowledge(userMessage) {
  if (!userMessage || typeof userMessage !== 'string') return null;

  const msg = userMessage.toLowerCase().trim();

  // 过短的消息不参与匹配，避免误触发
  if (msg.length < 2) return null;

  let bestMatch = null;
  let maxScore = 0;

  for (const entry of KNOWLEDGE_BASE) {
    let score = 0;
    for (const keyword of entry.keywords) {
      const kw = keyword.toLowerCase();
      // 2字符词误判风险高（如 客服/隐私/勋章），词表中已用更长短语替代，这里直接跳过
      if (kw.length < 3) continue;
      if (msg.includes(kw)) {
        // 关键词越长，得分越高（更精确匹配）
        score += kw.length;
      }
    }
    if (score > maxScore) {
      maxScore = score;
      bestMatch = entry;
    }
  }

  // 必须命中一个 ≥4 字符的意图短语才抢答，短词命中一律放行给 AI
  if (maxScore >= 4 && bestMatch) {
    return bestMatch.answer;
  }

  return null;
}

